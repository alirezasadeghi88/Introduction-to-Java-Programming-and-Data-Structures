public class MultiplicationTable {
    public static void main(String[] args) {
        System.out.println("Multiplication Table");

        System.out.print("   ");
        for (int j = 1; j <= 9; j++)
            System.out.print("   " + j);

        System.out.println("\n — — — — — — — — — — —— — — — — — — — —");
    }
}
